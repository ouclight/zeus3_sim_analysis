
module   wl_rst_sync_aux
     (
     clk_i          ,
     rst_n_i        ,
     rst_n_sync_o   
     );
//---------------------------------------------------------------------------------------
//port list
//---------------------------------------------------------------------------------------
input                   clk_i           ;//clk in
input                   rst_n_i         ;//rst in
output                  rst_n_sync_o    ;//rst sync out

//---------------------------------------------------------------------------------------
//process signal
//---------------------------------------------------------------------------------------
reg         s_syn_rst1_n;
reg         s_syn_rst2_n;
reg         s_syn_rst3_n;

//---------------------------------------------------------------------------------------
//code start
//---------------------------------------------------------------------------------------
always @ (posedge clk_i or negedge rst_n_i)
    if(!rst_n_i)
        begin
            s_syn_rst1_n <= 1'b0;
            s_syn_rst2_n <= 1'b0;
            s_syn_rst3_n <= 1'b0;
        end
    else
        begin
            s_syn_rst1_n <= 1'b1;
            s_syn_rst2_n <= s_syn_rst1_n;
            s_syn_rst3_n <= s_syn_rst2_n;
        end

assign  rst_n_sync_o = s_syn_rst3_n;

//---------------------------------------------------------------------------------------
//code end
//---------------------------------------------------------------------------------------
endmodule
